/** @typedef {'es'|'en'} Lang */

/** @returns {Lang} */
export function detectLang() {
  try {
    const p = window.location.pathname;
    return p === '/en' || p.startsWith('/en/') ? 'en' : 'es';
  } catch {
    return 'es';
  }
}

